const BY_ID: ReadonlyMap<string, LabelEntry> = new Map(LABEL_ENTRIES.map(entry => [entry.id, entry]))

const has = (table: Readonly<Record<string, string>>, key: string): boolean => Object.hasOwn(table, key)

/** One lower-case word as shown: an acronym in its usual casing (also with
 *  trailing digits, `uart0` to `UART0`), a voltage such as `3v3` as `3V3`,
 *  anything else unchanged. */
function word(token: string): string {
  if (has(ACRONYMS, token)) return ACRONYMS[token]
  const stem = token.replace(/\d+$/, '')
  if (stem !== '' && stem.length < token.length && has(ACRONYMS, stem)) return ACRONYMS[stem] + token.slice(stem.length)
  return /^\d+v\d+$/.test(token) ? token.toUpperCase() : token
}

/** An id as a sentence: split on `_`, `-` and spaces, acronyms restored, first
 *  word capitalised. Never returns an underscore. */
export function humanise(id: string): string {
  const tokens = id.toLowerCase().split(/[_\- ]+/).filter(token => token !== '')
  return tokens.map((token, i) => {
    const shown = word(token)
    if (i > 0 || has(ACRONYMS, token) || shown !== token) return shown
    return shown.charAt(0).toUpperCase() + shown.slice(1)
  }).join(' ')
}

/** `simavr:atmega328p` as `ATMEGA328P (simavr)`, for a backend the table does not list. */
function backendLabel(id: string): string | null {
  const at = id.indexOf(':')
  if (at < 0) return null
  const kind = id.slice(0, at)
  const part = id.slice(at + 1)
  return part !== '' && has(BACKEND_KINDS, kind) ? `${part.toUpperCase()} (${BACKEND_KINDS[kind]})` : null
}

/** The words for an internal id: its table label, an emulator backend as
 *  `ATmega328P (simavr)`, or the id humanised. Never the raw snake_case. */
export function labelFor(id: string | null | undefined): string {
  if (!id) return ''
  return BY_ID.get(id)?.label ?? backendLabel(id) ?? humanise(id)
}

/** The one-line explanation for an id, for a tooltip; `undefined` when the table has none. */
export function explainFor(id: string | null | undefined): string | undefined {
  return id ? BY_ID.get(id)?.explain : undefined
}
