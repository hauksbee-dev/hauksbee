// The generated GitHub Actions workflow, in one place. Both the Checks pane
// and the Export menu hand it out, and a second copy of the YAML is exactly
// where an immutable Action commit drifts back into a mutable tag.

import { ACTION_REPOSITORY, RELEASE_COMMIT, RELEASE_TAG } from './version'

export const workflowExportAvailable = /^[0-9a-f]{40}$/.test(RELEASE_COMMIT)

/** The spec file's stem for a board file name: `watchy.kicad_pcb` -> `watchy`.
 *  Names the downloaded spec and the `spec:` path inside the workflow, so the
 *  two always agree. */
export function specStemFor(boardFileName: string): string {
  const stem = (boardFileName || 'board').replace(/\.[^.]+$/, '')
  // This value becomes both a path segment and an unquoted YAML scalar. Keep
  // the shared exported/downloaded name portable and incapable of adding a
  // comment, newline, traversal, or a second workflow field.
  return stem
    .normalize('NFKD')
    .replace(/[^A-Za-z0-9._-]+/g, '-')
    .replace(/^[.-]+|[.-]+$/g, '') || 'board'
}

/** The spec file's placeholder in an engine message, such as the stopped-run
 *  message's `hauksbee-ci run <spec.toml>`. Mirrors
 *  hauksbee_ir::vocabulary::CHECK_RUN_CLI_COMMAND; a drift test in that crate
 *  holds the two equal. The page replaces it with the real file name. */
export const SPEC_FILE_PLACEHOLDER = '<spec.toml>'

/** An engine message with the spec placeholder named for the spec this page
 *  is showing, so the command the person copies names the file they downloaded. */
export function namedSpecIn(message: string | undefined, specFileName: string): string | undefined {
  return message?.split(SPEC_FILE_PLACEHOLDER).join(specFileName)
}

/** What a development build shows where a released build shows the pinned
 *  commit. Not a 40-hex commit, so a copy of the preview cannot run. */
const UNPINNED = 'PIN-A-RELEASE-COMMIT'

/** `.github/workflows/hauksbee-ci.yml`, pinned to THIS build's release commit. */
export function workflowYaml(specStem: string): string {
  if (!workflowExportAvailable) {
    throw new Error('This development build has no immutable release commit; install a released Hauksbee build before exporting the CI workflow.')
  }
  return renderWorkflow(specStem, RELEASE_COMMIT, RELEASE_TAG)
}

/** The same workflow with a placeholder where the release commit goes, so a
 *  development build can show what the file looks like. Never offered for
 *  download or export. */
export function workflowPreviewYaml(specStem: string): string {
  return renderWorkflow(specStem, UNPINNED, UNPINNED)
}

function renderWorkflow(specStem: string, commit: string, tag: string): string {
  return `# .github/workflows/hauksbee-ci.yml
# Generated by hauksbee ${tag}. Action code is pinned to the exact
# release commit; release assets are independently bound to the same ref below.
name: hardware-ci
on:
  push:
    paths: ["ci/**", "*.toml", ".github/workflows/**", "hardware/**", "firmware/**", "models/**", "**/*.kicad_pcb", "**/*.kicad_sch", "**/*.net", "**/*.brd", "**/*.PcbDoc", "**/*.d356", "**/*.xml", "**/*.zip", "**/*.tgz", "**/*.tar.gz", "**/*.tar"]
  pull_request:
    paths: ["ci/**", "*.toml", ".github/workflows/**", "hardware/**", "firmware/**", "models/**", "**/*.kicad_pcb", "**/*.kicad_sch", "**/*.net", "**/*.brd", "**/*.PcbDoc", "**/*.d356", "**/*.xml", "**/*.zip", "**/*.tgz", "**/*.tar.gz", "**/*.tar"]
concurrency:
  group: hauksbee-\${{ github.workflow }}-\${{ github.ref }}
  cancel-in-progress: true
permissions:
  contents: read
  checks: write
jobs:
  checks:
    runs-on: ubuntu-latest
    timeout-minutes: 45
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4.4.0
        with:
          persist-credentials: false
      - name: hauksbee-ci
        uses: ${ACTION_REPOSITORY}/integrations/github-action@${commit}
        with:
          hauksbee-ref: ${commit}
          hauksbee-version: ${tag}
          spec: ci/${specStem}.toml
          junit: hauksbee-ci-results.xml
          publish-report: \${{ github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository }}
`
}
