use std::path::{Path, PathBuf};

/// Validate a firmware path BEFORE it is handed to a native emulator backend.
///
/// simavr's `read_ihex_file` / `elf_read_firmware` (and the QEMU/Renode loaders)
/// do not defend against a missing file: given a path that does not exist they
/// print libc's "No such file or directory" to stderr and then dereference a
/// null result, crashing the whole process with SIGSEGV (exit 139) instead of
/// returning an error. This guard turns that into a clean, actionable failure.
///
/// On success it returns the resolved absolute path (the caller can canonicalize
/// it further once existence is guaranteed). On failure the error names the
/// absolute path that was tried and says whether it was missing, a directory,
/// or unreadable. Callers with extra provenance (e.g. a CI spec field) should
/// wrap this error to add where the path came from.
///
/// # Errors
///
/// When the path does not exist, names a directory, or cannot be opened for
/// reading.
pub fn validate_firmware_path(path: &Path) -> anyhow::Result<PathBuf> {
    // Absolute for the message without requiring existence (`canonicalize`
    // fails on a missing path, which is the case being diagnosed).
    let abs = std::path::absolute(path).unwrap_or_else(|_| path.to_path_buf());
    match std::fs::metadata(path) {
        Ok(md) if md.is_dir() => anyhow::bail!(
            "firmware path is a directory, not a file: {}",
            abs.display()
        ),
        // Readability: open it now so a permission problem surfaces here with
        // a clean message rather than deep inside the native loader.
        Ok(_) => std::fs::File::open(path)
            .map(|_| abs.clone())
            .map_err(|e| anyhow::anyhow!("firmware file is not readable: {} ({e})", abs.display())),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            anyhow::bail!("no firmware file at {}", abs.display())
        }
        Err(e) => anyhow::bail!("cannot access firmware file {}: {e}", abs.display()),
    }
}

/// Check a firmware file's extension and leading bytes BEFORE any board
/// analysis.
///
/// A format no backend loads is then refused in milliseconds rather than
/// after a long bind. `.uf2` and `.zip` are expected to have been
/// converted by the firmware-input layer already; a raw `.bin` is accepted
/// here (the Espressif backend boots merged flash images) and checked by the
/// backend that loads it.
///
/// # Errors
///
/// When the extension is not one any backend loads, or the content does not
/// match the format its extension claims.
pub fn validate_firmware_format(path: &Path) -> anyhow::Result<()> {
    use std::io::Read;
    let ext = path
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("")
        .to_ascii_lowercase();
    let mut head = [0u8; 4];
    let n = std::fs::File::open(path).and_then(|mut f| f.read(&mut head))?;
    let head = &head[..n];
    let is_elf = head == b"\x7fELF";
    let ok = match ext.as_str() {
        "elf" | "" => is_elf,
        "hex" | "ihex" => head.iter().find(|b| !b.is_ascii_whitespace()) == Some(&b':'),
        "bin" => true,
        _ => anyhow::bail!(
            "unsupported firmware extension '.{ext}' ({}); supported formats are .elf, \
             .hex, .uf2 (converted to Intel HEX on input) and a merged ESP flash .bin. \
             Convert it to Intel HEX first, e.g. `objcopy -O ihex {} firmware.hex` \
             (use your toolchain's objcopy, such as arm-none-eabi-objcopy; add \
             `-I srec` or `-I binary` for an input objcopy cannot detect)",
            path.display(),
            path.display()
        ),
    };
    if !ok {
        let want = if ext == "hex" || ext == "ihex" {
            "an Intel HEX file (lines starting ':')"
        } else {
            "an ELF image"
        };
        anyhow::bail!(
            "firmware {} is not {want}; its contents do not match its extension",
            path.display()
        );
    }
    Ok(())
}

