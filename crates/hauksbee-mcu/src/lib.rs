/// An emulator backend this machine does not have installed (Renode, Espressif
/// QEMU). Its message already names the install command.
///
/// A distinct type, not a bare message, so a caller can tell "the spec is wrong"
/// from "the tool the spec needs is not here" without matching on prose: the
/// first is the author's to fix, the second is an install.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BackendNotInstalled(pub String);

impl std::fmt::Display for BackendNotInstalled {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for BackendNotInstalled {}

/// Immutable simavr source revision linked into a provenance-bound AVR build.
///
/// Ordinary local system-library builds may not carry this optional identity;
/// release and CI builds require it and expose it through `doctor --backends`.
#[cfg(feature = "avr")]
pub const SIMAVR_BUILD_COMMIT: Option<&str> = option_env!("HAUKSBEE_SIMAVR_COMMIT");

/// Human-readable provenance for the built-in AVR backend. Shared by CLI and
/// MCP so the two public capability surfaces cannot drift.
#[cfg(feature = "avr")]
#[must_use]
pub fn simavr_build_detail() -> String {
    SIMAVR_BUILD_COMMIT.map_or_else(
        || "simavr linked into this binary (source commit not embedded)".to_string(),
        |commit| format!("simavr linked into this binary; source commit {commit}"),
    )
}

#[cfg(test)]
mod firmware_guard_tests {
    use super::validate_firmware_path;
    use std::path::Path;

    #[test]
    fn missing_file_errors_with_absolute_path() {
        let err = validate_firmware_path(Path::new("definitely_missing_firmware.hex"))
            .expect_err("missing firmware must error");
        let msg = err.to_string();
        assert!(msg.contains("no firmware file"), "message: {msg}");
        // The tried path is reported absolutely, not as the bare relative typo.
        assert!(
            msg.contains("definitely_missing_firmware.hex"),
            "message: {msg}"
        );
        assert!(
            Path::new(msg.rsplit(' ').next().unwrap_or("")).is_absolute() || msg.contains('/'),
            "message names an absolute path: {msg}"
        );
    }

    #[test]
    fn format_is_checked_from_extension_and_content() {
        use super::validate_firmware_format;
        let dir = std::env::temp_dir().join(format!("hauksbee-fw-fmt-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let write = |name: &str, bytes: &[u8]| {
            let p = dir.join(name);
            std::fs::write(&p, bytes).unwrap();
            p
        };
        // Legal controls.
        validate_firmware_format(&write("a.hex", b":00000001FF\n")).unwrap();
        validate_firmware_format(&write("a.elf", b"\x7fELF\x01\x01")).unwrap();
        validate_firmware_format(&write("a.bin", &[0xE9, 0, 0, 0])).unwrap();
        // Failing inputs.
        let err = validate_firmware_format(&write("a.srec", b"S0")).unwrap_err();
        assert!(
            err.to_string()
                .contains("unsupported firmware extension '.srec'"),
            "{err}"
        );
        assert!(err.to_string().contains("objcopy -O ihex"), "{err}");
        let err = validate_firmware_format(&write("b.hex", b"\x7fELF")).unwrap_err();
        assert!(err.to_string().contains("Intel HEX"), "{err}");
        let err = validate_firmware_format(&write("b.elf", b":0000")).unwrap_err();
        assert!(err.to_string().contains("ELF"), "{err}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn directory_is_rejected() {
        let dir = std::env::temp_dir();
        let err = validate_firmware_path(&dir).expect_err("a directory is not firmware");
        assert!(err.to_string().contains("directory"), "message: {err}");
    }

    #[test]
    fn readable_file_is_accepted_and_absolutized() {
        let mut path = std::env::temp_dir();
        path.push(format!("hauksbee-fw-guard-{}.hex", std::process::id()));
        std::fs::write(&path, b":00000001FF\n").expect("write temp firmware");
        let resolved = validate_firmware_path(&path).expect("existing readable file is valid");
        assert!(resolved.is_absolute());
        let _ = std::fs::remove_file(&path);
    }
}
